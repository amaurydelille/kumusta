export function glossVietnameseSentence(vietnamese: string): OfflineWordGloss[] {
  const sourceTokens = vietnamese.trim().split(/\s+/u);
  const normalized = sourceTokens.map(normalizeToken);
  const output: OfflineWordGloss[] = [];
  for (let index = 0; index < sourceTokens.length;) {
    const compound = index + 1 < sourceTokens.length
      ? `${normalized[index]} ${normalized[index + 1]}`
      : "";
    const compoundEnglish = COMPOUND_GLOSSES[compound];
    if (compoundEnglish) {
      output.push({
        token: `${sourceTokens[index]} ${sourceTokens[index + 1]}`,
        english: compoundEnglish,
      });
      index += 2;
      continue;
    }
    const word = normalized[index];
    const english = SINGLE_GLOSSES[word];
    if (!english) throw new Error(`Missing manual word gloss for "${word}" in: ${vietnamese}`);
    output.push({ token: sourceTokens[index], english });
    index += 1;
  }
  return output;
}

function normalizeToken(value: string): string {
  return value
    .normalize("NFC")
    .toLocaleLowerCase("vi")
    .replace(/[\p{P}\p{S}]+/gu, "");
}
