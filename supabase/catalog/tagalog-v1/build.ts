// Builds the authored Tagalog roadmap: validates every lesson against the
// lesson contract, then writes the catalog JSON (server copy and bundled app
// seed) and the seed migration.
//
//   deno run --allow-read --allow-write supabase/catalog/tagalog-v1/build.ts
import { buildRoadmap, type BuiltRoadmapLesson, type RoadmapLevel } from "./catalog.ts";
import { beginnerLessons } from "./beginner.ts";
import { beginnerLexicon } from "./lexicon-beginner.ts";
import { intermediateLessons } from "./intermediate.ts";
import { intermediateLexicon } from "./lexicon-intermediate.ts";
import { advancedLessons } from "./advanced.ts";
import { advancedLexicon } from "./lexicon-advanced.ts";
import { sharedLexicon } from "./lexicon-shared.ts";

const seedMigrationName = "20261025000100_seed_tagalog_roadmap_v1.sql";

const levels: Array<
  {
    level: RoadmapLevel;
    uuidFamily: string;
    lessons: typeof beginnerLessons;
    lexicon: Record<string, string>;
  }
> = [
  { level: "beginner", uuidFamily: "4301", lessons: beginnerLessons, lexicon: beginnerLexicon },
  {
    level: "intermediate",
    uuidFamily: "4302",
    lessons: intermediateLessons,
    lexicon: intermediateLexicon,
  },
  { level: "advanced", uuidFamily: "4303", lessons: advancedLessons, lexicon: advancedLexicon },
];

const root = new URL("../../../", import.meta.url);
const onlyLevel = Deno.args[0] as RoadmapLevel | undefined;
const allRows: BuiltRoadmapLesson[] = [];

for (const { level, uuidFamily, lessons, lexicon } of levels) {
  if (onlyLevel && onlyLevel !== level) continue;
  const rows = await buildRoadmap(lessons, {
    level,
    expectedLessonCount: 10,
    uuidFamily,
    lexicon: { ...sharedLexicon, ...lexicon },
  });
  allRows.push(...rows);
  const json = `${
    JSON.stringify({ version: 1, roadmap: `${level}-v1`, lessons: rows }, null, 2)
  }\n`;
  await Deno.writeTextFile(new URL(`supabase/catalog/${level}-tagalog-v1.json`, root), json);
  await Deno.writeTextFile(new URL(`Kumusta/Resources/Seed/${level}-tagalog-v1.json`, root), json);
  console.log(`${level}: validated ${rows.length} lessons.`);
}

if (!onlyLevel) {
  await Deno.writeTextFile(
    new URL(`supabase/migrations/${seedMigrationName}`, root),
    renderSeedMigration(allRows),
  );
  console.log(`Wrote ${seedMigrationName} with ${allRows.length} rows.`);
}

function renderSeedMigration(rows: BuiltRoadmapLesson[]): string {
  const values = rows.map((lesson) =>
    `(
    '${lesson.id}'::uuid,
    ${literal(lesson.slug)}, ${literal(lesson.content.title)}, ${literal(lesson.summary)},
    ${literal(lesson.level)}, ${lesson.estimatedMinutes}, ${lesson.sortOrder}, false, 1,
    ${literal(lesson.roadmapVersion)}, ${literal(lesson.unitSlug)}, ${literal(lesson.unitTitle)},
    ${lesson.unitOrder}, ${lesson.lessonOrder}, ${lesson.schemaVersion}, ${lesson.promptVersion},
    ${lesson.difficulty.toFixed(2)}, ${arrayLiteral(lesson.goalTags)}, ${
      literal(lesson.contentSource)
    }, ${literal(lesson.reviewStatus)},
    ${jsonLiteral(lesson.content)}, ${literal(lesson.contentHash)}, ${
      jsonLiteral(lesson.validation)
    }
  )`
  ).join(",\n");
  return `-- Generated by supabase/catalog/tagalog-v1/build.ts. Do not edit by hand.
-- The authored Tagalog roadmap: 10 lessons each for beginner, intermediate and
-- advanced. Rows stay unpublished (the schema only allows publishing approved
-- rows) until a native speaker signs off; the app ships the same lessons as
-- bundled seeds meanwhile.
begin;

insert into public.kumusta_lessons (
  id, slug, title, summary, level, estimated_minutes, sort_order,
  is_published, content_version, roadmap_version, unit_slug, unit_title,
  unit_order, lesson_order, schema_version, prompt_version, difficulty,
  goal_tags, content_source, review_status, content, content_hash, validation
) values
${values}
on conflict (slug) do update set
  title = excluded.title,
  summary = excluded.summary,
  level = excluded.level,
  estimated_minutes = excluded.estimated_minutes,
  sort_order = excluded.sort_order,
  is_published = false,
  content_version = excluded.content_version,
  roadmap_version = excluded.roadmap_version,
  unit_slug = excluded.unit_slug,
  unit_title = excluded.unit_title,
  unit_order = excluded.unit_order,
  lesson_order = excluded.lesson_order,
  schema_version = excluded.schema_version,
  prompt_version = excluded.prompt_version,
  difficulty = excluded.difficulty,
  goal_tags = excluded.goal_tags,
  content_source = excluded.content_source,
  review_status = 'native_speaker_review_required',
  editorial_review = '{}'::jsonb,
  content = excluded.content,
  content_hash = excluded.content_hash,
  validation = excluded.validation,
  updated_at = now();

commit;
`;
}

function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function arrayLiteral(values: string[]): string {
  return `array[${values.map(literal).join(", ")}]::text[]`;
}

function jsonLiteral(value: unknown): string {
  return `${literal(JSON.stringify(value))}::jsonb`;
}
